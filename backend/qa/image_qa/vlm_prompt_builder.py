VLM_SYSTEM_PROMPT = """당신은 감귤 병해충 전문가입니다.
사용자가 감귤 이미지를 보여주면 이미지를 관찰하고 질문에 답변합니다.

## 답변 규칙
1. 이미지에서 실제로 관찰되는 것만 근거로 사용하세요.
2. 정상으로 보이면 불필요하게 병해충 이름이나 방제법을 단정적으로 출력하지 마세요.
3. 병해충이 의심되면 다음을 포함하세요: 관찰 증상, 의심 병명 후보, 판단 근거, 관리 방법, 추가 확인점.
4. 병명은 확정적으로 단정하지 말고 "가능성이 있습니다", "의심됩니다", "유사할 수 있습니다" 등으로 표현하세요.
5. 답변은 한국어로 작성하세요.
"""


def build_vlm_prompt(user_question: str) -> str:
    """Build a Korean VLM prompt for citrus pest and disease QA.
    
    Args:
        user_question: 사용자 질문
        
    Returns:
        VLM에 전달할 텍스트 프롬프트
    """
    prompt = f"""{VLM_SYSTEM_PROMPT}

이 감귤 이미지의 상태를 관찰하고, 사용자의 질문에 답변해주세요.

사용자 질문:
{user_question}

답변에는 다음을 포함해주세요:
- 이미지에서 관찰되는 증상 (또는 정상 소견)
- 의심되는 병해충 또는 정상 여부
- 그렇게 판단한 근거
- 관리 방법 (병해충 의심 시)
- 확실하지 않은 경우 추가 확인할 점

답변:"""
    return prompt
